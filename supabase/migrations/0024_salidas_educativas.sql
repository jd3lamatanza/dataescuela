create or replace function public._salida_estado_id(p_nombre text) returns bigint
language sql stable set search_path = public as $$ select id from public.salida_estados where nombre = p_nombre $$;

-- ¿La salida es de la escuela que opera la sesión y todavía se puede modificar?
create or replace function public.salida_editable(p_id bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from public.salidas s
    where s.id = p_id and public.app_role() = 'escolar' and s.user_id = public.eff_uid()
      and s.estado_id in (public._salida_estado_id('Pendiente'), public._salida_estado_id('Devuelta para Corrección')))
$$;

create or replace function public.salida_es_dueno(p_id bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.salidas s where s.id = p_id and public.app_role() = 'escolar' and s.user_id = public.eff_uid())
$$;

create or replace function public._salida_validar(p_titulo text, p_fecha date, p_destino text, p_obs text) returns void
language plpgsql as $$
begin
  if length(trim(coalesce(p_titulo, ''))) < 3 then raise exception 'Completá el título'; end if;
  if p_fecha is null then raise exception 'Elegí la fecha'; end if;
  if length(trim(coalesce(p_destino, ''))) < 2 then raise exception 'Completá el destino'; end if;
  if length(coalesce(p_obs, '')) > 3000 then raise exception 'Las observaciones son demasiado largas'; end if;
end $$;

create or replace function public.salida_crear(p_titulo text, p_fecha date, p_destino text, p_obs text default null, p_mail boolean default true) returns bigint
language plpgsql security definer set search_path = public as $$
declare v_uid uuid := public.eff_uid(); e public.escuelas; v_id bigint;
begin
  if public.app_role() is distinct from 'escolar' then raise exception 'Solo las escuelas cargan salidas educativas'; end if;
  perform public._salida_validar(p_titulo, p_fecha, p_destino, p_obs);
  select * into e from public.escuelas where cue = public.app_cue() order by id limit 1;
  if not found then raise exception 'No se encontró la escuela de tu usuario'; end if;
  insert into public.salidas (user_id, cue, clave, escuela, titulo, fecha, destino, observaciones, estado_id, enviar_mail)
  values (v_uid, e.cue, e.clave, trim(concat_ws(' ', e.tipo, e.numero::text, e.nombre)), trim(p_titulo), p_fecha, trim(p_destino),
          nullif(trim(p_obs), ''), public._salida_estado_id('Pendiente'), coalesce(p_mail, true))
  returning id into v_id;
  return v_id;
end $$;

create or replace function public.salida_editar(p_id bigint, p_titulo text, p_fecha date, p_destino text, p_obs text default null) returns void
language plpgsql security definer set search_path = public as $$
declare s public.salidas;
begin
  if not public.salida_editable(p_id) then raise exception 'La salida no se puede modificar en su estado actual'; end if;
  perform public._salida_validar(p_titulo, p_fecha, p_destino, p_obs);
  select * into s from public.salidas where id = p_id;
  update public.salidas set titulo = trim(p_titulo), fecha = p_fecha, destino = trim(p_destino), observaciones = nullif(trim(p_obs), ''),
    estado_id = public._salida_estado_id('Pendiente'), updated_at = now() where id = p_id;
  if s.estado_id = public._salida_estado_id('Devuelta para Corrección') then
    insert into public.salida_mensajes (salida_id, user_id, rol, autor, texto, estado_id)
    select p_id, s.user_id, 'escolar', s.escuela, 'La escuela corrigió la salida y la reenvió.', public._salida_estado_id('Pendiente');
  end if;
end $$;

create or replace function public.salida_mensaje(p_id bigint, p_texto text) returns void
language plpgsql security definer set search_path = public as $$
declare v_rol text := public.app_role(); v_uid uuid := public.eff_uid(); s public.salidas; v_autor text;
begin
  select * into s from public.salidas where id = p_id;
  if not found then raise exception 'Salida inexistente'; end if;
  if not (v_rol = 'distrital' or (v_rol = 'escolar' and s.user_id = v_uid)) then raise exception 'Sin permiso'; end if;
  if length(trim(coalesce(p_texto, ''))) < 1 then raise exception 'Escribí un mensaje'; end if;
  select name into v_autor from public.profiles where id = v_uid;
  insert into public.salida_mensajes (salida_id, user_id, rol, autor, texto) values (p_id, v_uid, v_rol, v_autor, trim(p_texto));
end $$;

-- Solo el distrital cambia el estado. Al aprobar se agrega el evento al calendario de la escuela; si deja de estar aprobada, se quita.
create or replace function public.salida_estado(p_id bigint, p_estado bigint, p_texto text default null) returns void
language plpgsql security definer set search_path = public as $$
declare s public.salidas; v_nombre text; v_ev bigint; v_autor text; v_tipo bigint;
begin
  if public.app_role() is distinct from 'distrital' then raise exception 'Solo el distrito cambia el estado'; end if;
  select * into s from public.salidas where id = p_id;
  if not found then raise exception 'Salida inexistente'; end if;
  select nombre into v_nombre from public.salida_estados where id = p_estado and activo;
  if v_nombre is null then raise exception 'Estado inválido'; end if;
  update public.salidas set estado_id = p_estado, updated_at = now() where id = p_id;

  if v_nombre = 'Aprobada' then
    select id into v_tipo from public.evento_tipos where nombre = 'Salida Educativa';
    select name into v_autor from public.profiles where id = s.user_id;
    if s.evento_id is null then
      insert into public.eventos (fecha, tipo_id, nombre, descripcion, user_id, rol, autor, cue)
      values (s.fecha, v_tipo, s.titulo, 'Destino: ' || s.destino || coalesce(E'\n' || s.observaciones, ''), s.user_id, 'escolar', coalesce(v_autor, s.escuela), s.cue)
      returning id into v_ev;
      update public.salidas set evento_id = v_ev where id = p_id;
    else
      update public.eventos set fecha = s.fecha, nombre = s.titulo, descripcion = 'Destino: ' || s.destino || coalesce(E'\n' || s.observaciones, '') where id = s.evento_id;
    end if;
  elsif s.evento_id is not null then
    delete from public.eventos where id = s.evento_id;
  end if;

  select name into v_autor from public.profiles where id = public.eff_uid();
  insert into public.salida_mensajes (salida_id, user_id, rol, autor, texto, estado_id)
  values (p_id, public.eff_uid(), 'distrital', coalesce(v_autor, 'Distrito'), coalesce(nullif(trim(p_texto), ''), 'Estado actualizado a ' || v_nombre || '.'), p_estado);
end $$;

grant execute on function public.salida_editable(bigint) to authenticated;
grant execute on function public.salida_es_dueno(bigint) to authenticated;
grant execute on function public.salida_crear(text, date, text, text, boolean) to authenticated;
grant execute on function public.salida_editar(bigint, text, date, text, text) to authenticated;
grant execute on function public.salida_mensaje(bigint, text) to authenticated;
grant execute on function public.salida_estado(bigint, bigint, text) to authenticated;
revoke execute on function public._salida_validar(text, date, text, text) from authenticated, anon, public;
