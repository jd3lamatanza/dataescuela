-- Salidas educativas: estados, solicitudes de las escuelas, archivos (en Google Drive) e hilo de seguimiento

create table public.salida_estados (
  id bigint generated by default as identity primary key,
  nombre text not null unique,
  color text not null check (color in ('green','blue','orange','red','cyan','violet','amber','slate')),
  orden integer not null default 0,
  activo boolean not null default true
);
alter table public.salida_estados enable row level security;
create policy salest_sel on public.salida_estados for select to authenticated using (true);
create policy salest_adm on public.salida_estados for all to authenticated using (public.is_admin()) with check (public.is_admin());

insert into public.salida_estados (nombre, color, orden) values
  ('Pendiente', 'amber', 1), ('Aprobada', 'green', 2), ('Rechazada', 'red', 3),
  ('Devuelta para Corrección', 'orange', 4), ('Fuera de Término', 'slate', 5), ('En Proceso', 'blue', 6);

create table public.salidas (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles (id) on delete cascade,
  cue text not null,
  clave text,
  escuela text not null,
  titulo text not null check (length(trim(titulo)) between 3 and 150),
  fecha date not null,
  destino text not null check (length(trim(destino)) between 2 and 200),
  observaciones text check (length(observaciones) <= 3000),
  estado_id bigint not null references public.salida_estados (id),
  enviar_mail boolean not null default true,
  mail_enviado_at timestamptz,
  drive_folder_id text,
  evento_id bigint references public.eventos (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index salidas_user_idx on public.salidas (user_id);
create index salidas_estado_idx on public.salidas (estado_id);

create table public.salida_archivos (
  id bigint generated by default as identity primary key,
  salida_id bigint not null references public.salidas (id) on delete cascade,
  nombre text not null,
  mime text,
  bytes bigint,
  drive_file_id text not null,
  created_at timestamptz not null default now()
);
create index salida_archivos_salida_idx on public.salida_archivos (salida_id);

create table public.salida_mensajes (
  id bigint generated by default as identity primary key,
  salida_id bigint not null references public.salidas (id) on delete cascade,
  user_id uuid not null references public.profiles (id),
  rol text not null,
  autor text not null,
  texto text not null check (length(trim(texto)) between 1 and 3000),
  estado_id bigint references public.salida_estados (id),   -- si el mensaje cambió el estado
  created_at timestamptz not null default now()
);
create index salida_mensajes_salida_idx on public.salida_mensajes (salida_id, id);

alter table public.salidas enable row level security;
alter table public.salida_archivos enable row level security;
alter table public.salida_mensajes enable row level security;

create policy salidas_sel on public.salidas for select to authenticated using (
  public.app_role() in ('admin','regional','distrital') or (public.app_role() = 'escolar' and user_id = public.eff_uid()));
create policy salarch_sel on public.salida_archivos for select to authenticated using (exists (select 1 from public.salidas s where s.id = salida_id));
create policy salmsg_sel on public.salida_mensajes for select to authenticated using (exists (select 1 from public.salidas s where s.id = salida_id));
