  ('Agenda Anticipada', 'calendar', 'blue', 'areal'),
  ('Agenda Distrital', 'flag', 'orange', 'distrital'),
  ('Suspensión', 'alert', 'red', 'escolar'),
  ('Evento Escolar', 'school', 'cyan', 'escolar');

create table public.eventos (
  id bigint generated by default as identity primary key,
  fecha date not null,
  tipo_id bigint not null references public.evento_tipos (id),
  nombre text not null check (length(trim(nombre)) between 3 and 150),
  descripcion text,
  user_id uuid not null references public.profiles (id) on delete cascade,
  rol text not null,
  autor text not null,
  cue text,                                   -- CUE de la escuela autora (para que el areal vea las de sus escuelas)
  para_roles text[] not null default '{}',    -- roles a los que el distrital asigna el evento
  created_at timestamptz not null default now()
);
create index eventos_fecha_idx on public.eventos (fecha);
create index eventos_user_idx on public.eventos (user_id);
create index eventos_cue_idx on public.eventos (cue);
alter table public.eventos enable row level security;

-- Lectura: distrital/admin/regional todo; cada usuario los propios; el areal los de sus escuelas asignadas;
-- y los asignados a su rol. La escritura es solo por las funciones de abajo.
create policy eventos_sel on public.eventos for select to authenticated using (
  public.app_role() in ('admin','regional','distrital')
  or user_id = public.eff_uid()
  or public.app_role() = any (para_roles)
  or (public.app_role() = 'areal' and cue is not null and exists (
        select 1 from public.escuelas e where e.cue = eventos.cue and e.clave = any (public.claves_asignadas())))
);

create or replace function public.evento_guardar(p_id bigint, p_fecha date, p_tipo bigint, p_nombre text, p_desc text default null, p_para text[] default '{}') returns bigint
language plpgsql security definer set search_path = public as $$
declare v_uid uuid := public.eff_uid(); v_rol text := public.app_role(); v_id bigint; v_para text[]; v_owner uuid; v_nombre text;
begin
  if v_rol is null then raise exception 'Sin permiso'; end if;
  if p_fecha is null then raise exception 'Elegí la fecha'; end if;
  if length(trim(coalesce(p_nombre, ''))) < 3 then raise exception 'Completá el nombre del evento'; end if;
  if length(coalesce(p_desc, '')) > 2000 then raise exception 'La descripción es demasiado larga'; end if;
  if not exists (select 1 from public.evento_tipos where id = p_tipo and activo and rol = v_rol) then
    raise exception 'Tu rol no puede crear ese tipo de evento';
  end if;
  v_para := case when v_rol = 'distrital'
    then coalesce((select array_agg(distinct r) from unnest(p_para) r where r in ('areal','escolar')), '{}') else '{}' end;
  if p_id is null then
    select name into v_nombre from public.profiles where id = v_uid;
    insert into public.eventos (fecha, tipo_id, nombre, descripcion, user_id, rol, autor, cue, para_roles)
    values (p_fecha, p_tipo, trim(p_nombre), nullif(trim(p_desc), ''), v_uid, v_rol, v_nombre, public.app_cue(), v_para)
    returning id into v_id;
  else
    select user_id into v_owner from public.eventos where id = p_id;
    if v_owner is null then raise exception 'Evento inexistente'; end if;
    if v_owner <> v_uid and v_rol <> 'distrital' then raise exception 'Sin permiso'; end if;
    update public.eventos set fecha = p_fecha, tipo_id = p_tipo, nombre = trim(p_nombre), descripcion = nullif(trim(p_desc), ''),
      para_roles = case when v_owner = v_uid then v_para else para_roles end
    where id = p_id;
    v_id := p_id;
  end if;
  return v_id;
end $$;

create or replace function public.evento_eliminar(p_id bigint) returns void
language plpgsql security definer set search_path = public as $$
declare v_owner uuid;
begin
  select user_id into v_owner from public.eventos where id = p_id;
  if v_owner is null then raise exception 'Evento inexistente'; end if;
  if v_owner <> public.eff_uid() and public.app_role() is distinct from 'distrital' then raise exception 'Sin permiso'; end if;
  delete from public.eventos where id = p_id;
end $$;

grant execute on function public.evento_guardar(bigint, date, bigint, text, text, text[]) to authenticated;
grant execute on function public.evento_eliminar(bigint) to authenticated;
