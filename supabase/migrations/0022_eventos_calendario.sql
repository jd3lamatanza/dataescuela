-- Calendario del Home: tipos de evento y eventos

create table public.evento_tipos (
  id bigint generated by default as identity primary key,
  nombre text not null unique,
  icono text not null,
  color text not null check (color in ('green','blue','orange','red','cyan','violet','amber','slate')),
  rol text not null check (rol in ('admin','regional','distrital','areal','escolar')),  -- rol que puede crear este tipo
  activo boolean not null default true
);
alter table public.evento_tipos enable row level security;
create policy evtipo_sel on public.evento_tipos for select to authenticated using (true);
create policy evtipo_adm on public.evento_tipos for all to authenticated
  using (public.is_admin()) with check (public.is_admin());

insert into public.evento_tipos (nombre, icono, color, rol) values
