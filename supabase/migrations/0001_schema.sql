-- Esquema Postgres de DataEscuela (port de las migraciones D1/SQLite 0001-0020)
-- Convenciones: ids bigint identity (se conservan los ids de origen al importar),
-- flags como boolean, fechas como timestamptz, columnas en snake_case.

create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  legacy_id bigint unique,
  login text not null unique,           -- CUE, CUIL o usuario que se escribe en el login
  name text not null,
  role text not null check (role in ('admin','regional','distrital','areal','escolar')),
  active boolean not null default true,
  cue text,
  must_change boolean not null default false,
  created_at timestamptz not null default now()
);
create unique index profiles_login_lower on public.profiles (lower(login));

create table public.notifications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles (id) on delete cascade,
  type text not null default 'info' check (type in ('info','success','warning','error')),
  title text not null,
  body text,
  url text,
  read_at timestamptz,
  created_at timestamptz not null default now()
);
create index idx_notifications_user on public.notifications (user_id, read_at, id);

create table public.messages (
  id bigint generated by default as identity primary key,
  from_user_id uuid not null references public.profiles (id) on delete cascade,
  to_user_id uuid not null references public.profiles (id) on delete cascade,
  subject text not null,
  body text not null,
  read_at timestamptz,
  created_at timestamptz not null default now()
);
create index idx_messages_to on public.messages (to_user_id, read_at, id);

create table public.circuitos_electorales (
  id bigint generated by default as identity primary key,
  nombre text not null unique,
  activo boolean not null default true
);

create table public.nudos (
  id bigint generated by default as identity primary key,
  nombre text not null unique,
  activo boolean not null default true
);

create table public.catalogos (
  id bigint generated by default as identity primary key,
  coleccion text not null,
  codigo text,
  nombre text not null,
  valor double precision,
  orden integer not null default 0,
  activo boolean not null default true,
  unique (coleccion, nombre)
);
create index idx_catalogos_coleccion on public.catalogos (coleccion, activo, orden);

create table public.escuelas (
  id bigint generated by default as identity primary key,
  region text,
  distrital text,
  modalidad text,
  nivel text,
  clave text,
  cue text not null,
  codigo text,
  numero integer,
  tipo text,
  nombre text,
  localidad text,
  calle text,
  nu_calle integer,
  entre_calle text,
  entre_calle_2 text,
  cp integer,
  eav text,
  te text,
  email text,
  gestion text,
  dep text,
  ambito text,
  desf integer,
  sede text,
  cue_sede text,
  cat text,
  ultimo text,
  usuario text,
  alfa boolean not null default false,
  sede_electoral boolean not null default false,
  sede_evacuacion boolean not null default false,
  circuito_id bigint references public.circuitos_electorales (id),
  nudo_id bigint references public.nudos (id)
);
create index idx_escuelas_cue on public.escuelas (cue);
create index idx_escuelas_clave on public.escuelas (clave);

create table public.inspectores (
  id bigint generated by default as identity primary key,
  user_id uuid references public.profiles (id) on delete set null,
  nivel_o_modalidad text,
  nombre text,
  cuil text not null unique,
  situacion_revista text,
  cargo_base text,
  fecha_toma_posesion text,             -- dd/mm/aaaa
  telefono text,
  email text,
  escuelas_asignadas text[] not null default '{}'  -- claves provinciales
);

create table public.egresantes (
  id bigint generated by default as identity primary key,
  ciclo integer not null,
  dni text not null,
  nombre text not null,
  direccion text,
  curso text not null,
  ppi boolean not null default false,
  acompanante boolean not null default false,
  intensifica boolean not null default false,
  destino_clave text,
  destino_nombre text,
  destino_manual boolean not null default false,
  observaciones text,
  origen_cue text not null,
  origen_clave text not null,
  origen_codigo text,
  created_by uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz,
  doc_completa boolean not null default false,
  ingresado boolean not null default false,
  ext_escuela text,
  ext_at timestamptz,
  unique (ciclo, dni)
);
create index idx_egresantes_origen on public.egresantes (origen_cue, ciclo);
create index idx_egresantes_destino on public.egresantes (destino_clave, ciclo);

create table public.intervenciones (
  id bigint generated by default as identity primary key,
  egresante_id bigint not null references public.egresantes (id) on delete cascade,
  texto text not null,
  tipo text not null default 'intervencion',
  created_by uuid,
  created_by_name text not null,
  created_at timestamptz not null default now()
);
create index idx_intervenciones_egresante on public.intervenciones (egresante_id, created_at);

create table public.impersonaciones (
  id bigint generated by default as identity primary key,
  actor_id uuid not null references public.profiles (id),
  target_id uuid not null references public.profiles (id),
  started_at timestamptz not null default now(),
  ended_at timestamptz
);
create index idx_imp_actor on public.impersonaciones (actor_id, started_at);

create table public.equipo_directivo (
  id bigint generated by default as identity primary key,
  escuela_id bigint not null references public.escuelas (id),
  cargo_id bigint not null references public.catalogos (id),
  revista_id bigint references public.catalogos (id),
  apellido_nombre text not null,
  cuil text,
  fecha_nacimiento text,
  email text,
  telefono text,
  toma_posesion text,
  cargo_base text,
  activo boolean not null default true,
  updated_at timestamptz not null default now(),
  updated_by uuid
);
create index idx_ed_escuela on public.equipo_directivo (escuela_id, activo);

create table public.equipo_orientacion (
  id bigint generated by default as identity primary key,
  escuela_id bigint not null references public.escuelas (id),
  cargo_id bigint not null references public.catalogos (id),
  revista_id bigint references public.catalogos (id),
  apellido_nombre text not null,
  cuil text,
  fecha_nacimiento text,
  email text,
  telefono text,
  toma_posesion text,
  activo boolean not null default true,
  updated_at timestamptz not null default now(),
  updated_by uuid
);
create index idx_eoe_escuela on public.equipo_orientacion (escuela_id, activo);

create table public.referentes_esi (
  id bigint generated by default as identity primary key,
  escuela_id bigint not null references public.escuelas (id),
  apellido_nombre text not null,
  dni text,
  cargo text,
  area text,
  turno text,
  otra_escuela boolean not null default false,
  otra_escuela_detalle text,
  activo boolean not null default true,
  updated_at timestamptz not null default now(),
  updated_by uuid
);
create index idx_esi_escuela on public.referentes_esi (escuela_id, activo);

create table public.planes_estudio (
  id bigint generated by default as identity primary key,
  nombre text not null,
  nivel_id bigint not null references public.catalogos (id),
  modalidad_id bigint not null references public.catalogos (id),
  cantidad_cursos integer not null check (cantidad_cursos between 1 and 20),
  activo boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  updated_by uuid
);
create unique index planes_estudio_nombre_lower on public.planes_estudio (lower(nombre));
create index idx_planes_nivel on public.planes_estudio (nivel_id, modalidad_id, activo);

create table public.planes_cursos (
  id bigint generated by default as identity primary key,
  plan_id bigint not null references public.planes_estudio (id) on delete cascade,
  orden integer not null,
  nombre text not null,
  unique (plan_id, orden)
);

create table public.turnos (
  id bigint generated by default as identity primary key,
  nombre text not null,
  hora_desde text,
  hora_hasta text,
  activo boolean not null default true,
  updated_at timestamptz not null default now(),
  updated_by uuid
);
create unique index turnos_nombre_lower on public.turnos (lower(nombre));

create table public.plantas (
  id bigint generated by default as identity primary key,
  escuela_id bigint not null unique references public.escuelas (id),
  total_secciones integer not null,
  editable boolean not null default false,
  confirmada_at timestamptz not null default now(),
  updated_by uuid
);

create table public.planta_turnos (
  planta_id bigint not null references public.plantas (id) on delete cascade,
  turno_id bigint not null references public.turnos (id),
  primary key (planta_id, turno_id)
);

create table public.planta_secciones (
  planta_id bigint not null references public.plantas (id) on delete cascade,
  plan_id bigint not null references public.planes_estudio (id),
  curso_id bigint not null references public.planes_cursos (id),
  turno_id bigint not null references public.turnos (id),
  secciones integer not null check (secciones between 0 and 99),
  primary key (planta_id, curso_id, turno_id)
);

create table public.carga_activa (
  id bigint generated by default as identity primary key,
  ciclo integer not null,
  mes integer not null check (mes between 1 and 12),
  fecha_apertura date not null,
  fecha_cierre date not null,
  carga boolean not null default false,
  unique (ciclo, mes)
);

create table public.matricula_cargas (
  id bigint generated by default as identity primary key,
  escuela_id bigint not null references public.escuelas (id),
  ciclo integer not null,
  mes integer not null,
  habilitada boolean not null default false,
  confirmada_at timestamptz,
  updated_by uuid,
  unique (escuela_id, ciclo, mes)
);

create table public.matricula_datos (
  carga_id bigint not null references public.matricula_cargas (id) on delete cascade,
  plan_id bigint not null references public.planes_estudio (id),
  curso_id bigint not null references public.planes_cursos (id),
  turno_id bigint not null references public.turnos (id),
  secciones integer not null,
  matricula integer not null check (matricula >= 0),
  asistencia integer not null check (asistencia >= 0),
  primary key (carga_id, curso_id, turno_id)
);

create table public.ajustes (
  clave text primary key,
  valor text not null,
  updated_at timestamptz not null default now(),
  updated_by uuid
);

create table public.agrupamientos_matricula (
  id bigint generated by default as identity primary key,
  nombre text not null,
  updated_by uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index agrupamientos_nombre_lower on public.agrupamientos_matricula (lower(nombre));

create table public.agrupamiento_codigos (
  agrupamiento_id bigint not null references public.agrupamientos_matricula (id) on delete cascade,
  codigo text not null unique,
  primary key (agrupamiento_id, codigo)
);
