create or replace function public.disposicion_archivo_limite() returns trigger
language plpgsql set search_path = public as $$
begin
  perform pg_advisory_xact_lock(new.disposicion_id);
  if new.tipo = 'inicial' and (select count(*) from public.disposicion_archivos where disposicion_id = new.disposicion_id and tipo = 'inicial') >= 3 then
    raise exception 'Solo se permiten hasta 3 archivos de probanza inicial';
  end if;
  return new;
end $$;

