create function public.disposicion_areal_asignada(p_escuela bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce(public.app_role() = 'areal'
    and (public.real_role() in ('areal','distrital'))
    and exists (select 1 from public.escuelas e where e.id = p_escuela and e.clave = any(public.claves_asignadas())), false)
$$;
create function public.disposicion_acceso(p_id bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.disposiciones d where d.id = p_id
    and (public.disposiciones_permitido() or public.disposicion_areal_asignada(d.escuela_cubrir_id)))
$$;
create function public.disposicion_final_visible(p_id bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.disposiciones d where d.id = p_id and d.estado = 'Finalizada'
    and (public.disposicion_acceso(d.id)
      or (public.app_role() = 'escolar' and public.real_role() in ('escolar','distrital')
        and public.can_see_escuela(d.escuela_cubrir_id))))
$$;
revoke all on function public.disposicion_areal_asignada(bigint), public.disposicion_acceso(bigint), public.disposicion_final_visible(bigint) from public, anon;
grant execute on function public.disposicion_areal_asignada(bigint), public.disposicion_acceso(bigint), public.disposicion_final_visible(bigint) to authenticated;

