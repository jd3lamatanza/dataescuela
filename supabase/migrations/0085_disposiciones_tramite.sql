create or replace function public.disposicion_validar() returns trigger
language plpgsql security definer set search_path = public as $$
declare v_areal boolean := public.app_role() = 'areal';
begin
  if auth.uid() is null then return new; end if;
  if tg_op = 'UPDATE' and (to_jsonb(new) - 'leida_at') = (to_jsonb(old) - 'leida_at') then
    if not public.disposiciones_permitido() then raise exception 'Sin permiso'; end if;
    return new;
  end if;
  if tg_op = 'INSERT' then
    if not (public.disposiciones_permitido() or public.disposicion_areal_asignada(new.escuela_cubrir_id)) then raise exception 'Sin permiso'; end if;
    new.creado_por := public.eff_uid();
    new.creado_areal := v_areal;
    new.leida_at := null;
    new.estado := case when v_areal then 'Pendiente' else 'En proceso' end;
    new.fecha_registro := now();
    if v_areal then
      select i.nombre into new.inspector from public.inspectores i where i.user_id = public.eff_uid() order by i.id limit 1;
      if coalesce(btrim(new.inspector),'') = '' then raise exception 'No se encontró el inspector de tu cuenta'; end if;
    end if;
  else
    if not public.disposiciones_permitido() then raise exception 'Sin permiso'; end if;
    if new.estado = 'Finalizada' and old.estado is distinct from 'Finalizada' then raise exception 'Finalizá el trámite adjuntando el PDF'; end if;
    if old.estado = 'Finalizada' and new.estado is distinct from old.estado and exists (select 1 from public.disposicion_final f where f.disposicion_id = old.id) then
      raise exception 'Una disposición finalizada no puede cambiar de estado';
    end if;
    new.creado_por := old.creado_por;
    new.creado_areal := old.creado_areal;
    new.fecha_registro := old.fecha_registro;
  end if;
  select clave, coalesce(nullif(nombre, ''), concat_ws(' ', tipo, numero))
    into new.escuela_cubrir_clave, new.escuela_cubrir_nombre from public.escuelas where id = new.escuela_cubrir_id;
  if not found then raise exception 'Escuela a cubrir inexistente'; end if;
  if new.escuela_base_fuera_distrital then
    if new.escuela_base_id is not null or coalesce(btrim(new.escuela_base_nombre), '') = '' then raise exception 'Ingresá el nombre de la escuela fuera de la Distrital'; end if;
    new.escuela_base_nombre := btrim(new.escuela_base_nombre);
    new.escuela_base_clave := coalesce(btrim(new.escuela_base_clave), '');
  elsif new.escuela_base_id is null then
    if tg_op = 'INSERT' or old.escuela_base_id is not null or old.escuela_base_fuera_distrital then raise exception 'Seleccioná una escuela base'; end if;
    new.escuela_base_clave := old.escuela_base_clave;
    new.escuela_base_nombre := old.escuela_base_nombre;
  else
    select clave, coalesce(nullif(nombre, ''), concat_ws(' ', tipo, numero))
      into new.escuela_base_clave, new.escuela_base_nombre from public.escuelas where id = new.escuela_base_id;
    if not found then raise exception 'Escuela base inexistente'; end if;
  end if;
  if btrim(new.inspector) = '' or btrim(new.docente_nombre) = '' or new.docente_cuil !~ '^[0-9]+$'
    or new.email_jefatura !~* '^[^[:space:]@]+@abc\.gob\.ar$'
    or new.docente_email !~* '^[^[:space:]@]+@abc\.gob\.ar$'
    or new.cargo_cubrir not in ('Director','Vicedirector','Secretario','Prosecretario')
    or new.revista_cubrir not in ('Titular','Provisional','Suplente')
    or new.revista_base not in ('Titular','Provisional','Suplente')
    or btrim(new.numero_designacion) = '' or btrim(new.cargo_base) = '' then
    raise exception 'Completá los datos obligatorios con valores válidos';
  end if;
  select coalesce(nullif(name, ''), login) into new.usuario from public.profiles where id = public.eff_uid();
  new.actualizada := now();
  return new;
end $$;

create function public.disposicion_notificar() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if tg_op = 'INSERT' and new.creado_areal then
    insert into public.notifications(user_id,type,title,body,url)
    select p.id,'info',public.push_titulo('Nueva disposición',new.inspector),
      'Nueva disposición #' || new.id || ' · ' || new.escuela_cubrir_nombre, '/disposiciones'
    from public.profiles p where p.active and p.role = 'distrital';
  elsif tg_op = 'UPDATE' and old.estado is distinct from new.estado then
    insert into public.notifications(user_id,type,title,body,url)
    select distinct p.id,'info','Cambio de estado de disposición',
      'Disposición #' || new.id || ': ' || new.estado, '/disposiciones'
    from public.profiles p where p.active and p.role = 'areal'
      and (p.id = new.creado_por or exists (select 1 from public.inspectores i
        where i.user_id = p.id and new.escuela_cubrir_clave = any(i.escuelas_asignadas)));
  end if;
  return new;
end $$;
revoke all on function public.disposicion_notificar() from public, anon, authenticated;
create trigger disposicion_notificar after insert or update of estado on public.disposiciones
for each row execute function public.disposicion_notificar();

create function public.disposicion_marcar_leida(p_id bigint) returns void
language plpgsql security definer set search_path = public as $$
begin
  if not public.disposiciones_permitido() then raise exception 'Sin permiso'; end if;
  update public.disposiciones set leida_at = now() where id = p_id and creado_areal and leida_at is null;
end $$;
create function public.disposicion_comentar(p_id bigint, p_texto text) returns void
language plpgsql security definer set search_path = public as $$
declare v_rol text := public.app_role(); v_nombre text;
begin
  if not public.disposicion_acceso(p_id) then raise exception 'Sin permiso'; end if;
  if length(btrim(coalesce(p_texto,''))) not between 1 and 3000 then raise exception 'Escribí un mensaje de hasta 3000 caracteres'; end if;
  select coalesce(nullif(name,''),login) into v_nombre from public.profiles where id = public.eff_uid();
  insert into public.disposicion_mensajes(disposicion_id,user_id,autor,rol,texto)
  values (p_id,public.eff_uid(),v_nombre,v_rol,btrim(p_texto));
  if v_rol = 'areal' then
    insert into public.notifications(user_id,type,title,body,url)
    select p.id,'info',public.push_titulo('Respuesta a disposición',v_nombre), 'Disposición #' || p_id, '/disposiciones'
    from public.profiles p where p.active and p.role = 'distrital';
  end if;
end $$;
create function public.disposicion_cambiar_estado(p_id bigint, p_estado text, p_texto text default null) returns void
language plpgsql security definer set search_path = public as $$
begin
  if not public.disposiciones_permitido() then raise exception 'Sin permiso'; end if;
  if p_estado not in ('Pendiente','En proceso','Enviada a SAD','Rechazada','Devuelta para Corrección') then raise exception 'Estado inválido'; end if;
  if length(coalesce(p_texto,'')) > 3000 then raise exception 'El mensaje es demasiado largo'; end if;
  update public.disposiciones set estado = p_estado where id = p_id;
  if not found then raise exception 'Disposición inexistente'; end if;
  if nullif(btrim(coalesce(p_texto,'')),'') is not null then perform public.disposicion_comentar(p_id,p_texto); end if;
end $$;
create function public.disposicion_escuelas_listar()
returns table(id bigint, estado text, fecha_registro timestamptz, escuela_cubrir_nombre text, pdf_disponible boolean)
language plpgsql stable security definer set search_path = public as $$
begin
  if public.app_role() is distinct from 'escolar' or public.real_role() not in ('escolar','distrital') then raise exception 'Sin permiso'; end if;
  return query select d.id,d.estado,d.fecha_registro,d.escuela_cubrir_nombre,
    d.estado = 'Finalizada' and exists (select 1 from public.disposicion_final f where f.disposicion_id = d.id)
  from public.disposiciones d where public.can_see_escuela(d.escuela_cubrir_id) order by d.id desc;
end $$;
revoke all on function public.disposicion_marcar_leida(bigint), public.disposicion_comentar(bigint,text), public.disposicion_cambiar_estado(bigint,text,text), public.disposicion_escuelas_listar() from public, anon;
grant execute on function public.disposicion_marcar_leida(bigint), public.disposicion_comentar(bigint,text), public.disposicion_cambiar_estado(bigint,text,text), public.disposicion_escuelas_listar() to authenticated;

create function public.disposicion_finalizar_drive(p_id bigint, p_actor uuid, p_file_id text, p_nombre text, p_bytes bigint) returns void
language plpgsql security definer set search_path = public as $$
declare v_efectivo uuid;
begin
  select coalesce((select s.target_id from public.simulaciones s where s.actor_id = p_actor),p_actor) into v_efectivo;
  if v_efectivo <> p_actor or not exists (select 1 from public.profiles where id = p_actor and active and role = 'distrital') then raise exception 'Sin permiso'; end if;
  if p_file_id !~ '^[A-Za-z0-9_-]{10,}$' or length(btrim(coalesce(p_nombre,''))) not between 1 and 200 or p_bytes not between 1 and 10485760 then raise exception 'PDF inválido'; end if;
  perform 1 from public.disposiciones where id = p_id for update;
  if not found then raise exception 'Disposición inexistente'; end if;
  if exists (select 1 from public.disposicion_final where disposicion_id = p_id) then raise exception 'El trámite ya tiene un PDF final'; end if;
  insert into public.disposicion_final(disposicion_id,nombre,bytes,drive_file_id) values (p_id,btrim(p_nombre),p_bytes,p_file_id);
  update public.disposiciones set estado = 'Finalizada', actualizada = now() where id = p_id;
end $$;
revoke all on function public.disposicion_finalizar_drive(bigint,uuid,text,text,bigint) from public, anon, authenticated;
grant execute on function public.disposicion_finalizar_drive(bigint,uuid,text,text,bigint) to service_role;

