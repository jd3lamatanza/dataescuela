create table public.proyectos_areales_tipos (
  id bigint generated by default as identity primary key,
  nombre text not null check (length(btrim(nombre)) between 2 and 150),
  created_at timestamptz not null default now()
);
create unique index proyectos_areales_tipos_nombre_idx on public.proyectos_areales_tipos (lower(btrim(nombre)));
insert into public.proyectos_areales_tipos(nombre)
values ('Proyecto Areal'), ('Proyecto de Supervisión'), ('Proyecto de Articulación');

alter table public.proyectos_areales_tipos enable row level security;
revoke all on public.proyectos_areales_tipos from public, anon, authenticated;
grant select on public.proyectos_areales_tipos to authenticated;
grant all on public.proyectos_areales_tipos to service_role;
create policy proyectos_areales_tipos_sel on public.proyectos_areales_tipos for select to authenticated
  using (public.app_role() in ('areal', 'distrital'));

create table public.proyectos_areales (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id),
  tipo_id bigint references public.proyectos_areales_tipos(id) on delete restrict,
  otro_tipo text,
  nombre text not null check (length(btrim(nombre)) between 1 and 255),
  bytes integer not null check (bytes between 1 and 5242880),
  drive_file_id text not null unique,
  created_at timestamptz not null default now(),
  check ((tipo_id is null and otro_tipo is not null and length(btrim(otro_tipo)) between 1 and 150)
    or (tipo_id is not null and otro_tipo is null))
);
create index proyectos_areales_usuario_fecha_idx on public.proyectos_areales(user_id, created_at desc, id desc);
alter table public.proyectos_areales enable row level security;
revoke all on public.proyectos_areales from public, anon, authenticated;
grant select on public.proyectos_areales to authenticated;
grant all on public.proyectos_areales to service_role;
create policy proyectos_areales_sel on public.proyectos_areales for select to authenticated
  using (public.app_role() = 'distrital' or (public.app_role() = 'areal' and user_id = public.eff_uid()));

create table public.proyectos_areales_carpetas (
  user_id uuid primary key references public.profiles(id),
  nombre text not null,
  drive_folder_id text unique,
  reserva uuid,
  reservada_hasta timestamptz
);
alter table public.proyectos_areales_carpetas enable row level security;
revoke all on public.proyectos_areales_carpetas from public, anon, authenticated;
grant all on public.proyectos_areales_carpetas to service_role;

create function public.proyecto_areal_carpeta_reservar(p_user uuid, p_nombre text, p_reserva uuid) returns jsonb
language plpgsql security definer set search_path = public as $$
declare carpeta public.proyectos_areales_carpetas;
begin
  insert into public.proyectos_areales_carpetas(user_id, nombre) values (p_user, p_nombre) on conflict (user_id) do nothing;
  select * into carpeta from public.proyectos_areales_carpetas where user_id = p_user for update;
  if carpeta.drive_folder_id is not null then
    return jsonb_build_object('estado', 'lista', 'id', carpeta.drive_folder_id);
  end if;
  if carpeta.reservada_hasta > now() then return jsonb_build_object('estado', 'ocupada'); end if;
  update public.proyectos_areales_carpetas set nombre = p_nombre, reserva = p_reserva, reservada_hasta = now() + interval '2 minutes' where user_id = p_user;
  return jsonb_build_object('estado', 'reservada');
end $$;
create function public.proyecto_areal_carpeta_confirmar(p_user uuid, p_reserva uuid, p_carpeta text) returns boolean
language plpgsql security definer set search_path = public as $$
begin
  update public.proyectos_areales_carpetas set drive_folder_id = p_carpeta, reserva = null, reservada_hasta = null
    where user_id = p_user and reserva = p_reserva and drive_folder_id is null;
  return found;
end $$;
create function public.proyecto_areal_carpeta_liberar(p_user uuid, p_reserva uuid) returns void
language sql security definer set search_path = public as $$
  update public.proyectos_areales_carpetas set reserva = null, reservada_hasta = null where user_id = p_user and reserva = p_reserva
$$;
revoke all on function public.proyecto_areal_carpeta_reservar(uuid,text,uuid), public.proyecto_areal_carpeta_confirmar(uuid,uuid,text),
  public.proyecto_areal_carpeta_liberar(uuid,uuid) from public, anon, authenticated;
grant execute on function public.proyecto_areal_carpeta_reservar(uuid,text,uuid), public.proyecto_areal_carpeta_confirmar(uuid,uuid,text),
  public.proyecto_areal_carpeta_liberar(uuid,uuid) to service_role;

create function public.proyecto_areal_mi_inspector() returns text
language plpgsql stable security definer set search_path = public as $$
declare n integer; nombre text;
begin
  if public.app_role() is distinct from 'areal' then raise exception 'Sin permiso'; end if;
  select count(*), min(nullif(btrim(i.nombre), '')) into n, nombre from public.inspectores i where i.user_id = public.eff_uid();
  if n <> 1 or nombre is null then raise exception 'Tu cuenta no tiene un inspector con nombre único asociado. Consultá con la Jefatura.'; end if;
  return nombre;
end $$;
revoke all on function public.proyecto_areal_mi_inspector() from public, anon;
grant execute on function public.proyecto_areal_mi_inspector() to authenticated;

create function public.proyecto_areal_guardar_tipo(p_id bigint, p_nombre text) returns void
language plpgsql security definer set search_path = public as $$
begin
  if public.app_role() is distinct from 'distrital' then raise exception 'Sin permiso'; end if;
  p_nombre := btrim(coalesce(p_nombre, ''));
  if length(p_nombre) not between 2 and 150 or lower(p_nombre) = 'otro' then raise exception 'Ingresá un nombre válido para el tipo.'; end if;
  if p_id is null then insert into public.proyectos_areales_tipos(nombre) values (p_nombre);
  else
    update public.proyectos_areales_tipos set nombre = p_nombre where id = p_id;
    if not found then raise exception 'Tipo inexistente'; end if;
  end if;
exception when unique_violation then raise exception 'Ya existe un tipo con ese nombre.';
end $$;
create function public.proyecto_areal_eliminar_tipo(p_id bigint) returns void
language plpgsql security definer set search_path = public as $$
begin
  if public.app_role() is distinct from 'distrital' then raise exception 'Sin permiso'; end if;
  delete from public.proyectos_areales_tipos where id = p_id;
  if not found then raise exception 'Tipo inexistente'; end if;
exception when foreign_key_violation then raise exception 'No se puede eliminar un tipo que tiene proyectos cargados.';
end $$;
revoke all on function public.proyecto_areal_guardar_tipo(bigint,text), public.proyecto_areal_eliminar_tipo(bigint) from public, anon;
grant execute on function public.proyecto_areal_guardar_tipo(bigint,text), public.proyecto_areal_eliminar_tipo(bigint) to authenticated;

create function public.proyectos_areales_listar(
  p_busqueda text default '', p_tipo text default '', p_orden text default 'recientes',
  p_lim integer default 15, p_offset integer default 0
) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare resultado jsonb;
begin
  if public.app_role() not in ('areal', 'distrital') or public.app_role() is null then raise exception 'Sin permiso'; end if;
  if p_lim is null or p_lim < 1 or p_lim > 100 or p_offset is null or p_offset < 0 then raise exception 'Paginación inválida'; end if;
  if p_orden is null or p_orden not in ('recientes', 'antiguos', 'inspector', 'tipo', 'archivo') then raise exception 'Orden inválido'; end if;
  with filtradas as (
    select p.id, p.user_id, p.tipo_id, coalesce(t.nombre, p.otro_tipo) tipo, p.nombre, p.bytes, p.created_at,
      coalesce(i.nombre, u.name, 'Inspector sin nombre') inspector
    from public.proyectos_areales p join public.profiles u on u.id = p.user_id
    left join public.proyectos_areales_tipos t on t.id = p.tipo_id
    left join lateral (select nombre from public.inspectores where user_id = p.user_id order by id limit 1) i on true
    where (public.app_role() = 'distrital' or p.user_id = public.eff_uid())
      and (coalesce(p_tipo, '') = '' or (p_tipo = 'otro' and p.tipo_id is null) or p.tipo_id::text = p_tipo)
      and (coalesce(btrim(p_busqueda), '') = '' or concat_ws(' ', i.nombre, u.name, t.nombre, p.otro_tipo, p.nombre)
        ilike '%' || replace(replace(replace(btrim(p_busqueda), '\', '\\'), '%', '\%'), '_', '\_') || '%')
  ), ordenadas as (
    select *, row_number() over (order by
      case when p_orden = 'recientes' then created_at end desc,
      case when p_orden = 'antiguos' then created_at end asc,
      case when p_orden = 'inspector' then lower(inspector) end asc,
      case when p_orden = 'tipo' then lower(tipo) end asc,
      case when p_orden = 'archivo' then lower(nombre) end asc, id asc) posicion from filtradas
  ), pagina as (select * from ordenadas order by posicion limit p_lim offset p_offset)
  select jsonb_build_object('total', (select count(*) from filtradas),
    'filas', coalesce((select jsonb_agg(to_jsonb(pagina) - 'posicion' order by posicion) from pagina), '[]'::jsonb)) into resultado;
  return resultado;
end $$;
revoke all on function public.proyectos_areales_listar(text,text,text,integer,integer) from public, anon;
grant execute on function public.proyectos_areales_listar(text,text,text,integer,integer) to authenticated;

create function public.proyectos_areales_inspectores(p_busqueda text default '', p_lim integer default 15, p_offset integer default 0) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare resultado jsonb;
begin
  if public.app_role() is distinct from 'distrital' then raise exception 'Sin permiso'; end if;
  if p_lim is null or p_lim < 1 or p_lim > 100 or p_offset is null or p_offset < 0 then raise exception 'Paginación inválida'; end if;
  with filtradas as (
    select p.id, coalesce(i.nombre, p.name, 'Inspector sin nombre') nombre, i.nivel_o_modalidad,
      (select count(*) from public.proyectos_areales x where x.user_id = p.id) cantidad
    from public.profiles p
    left join lateral (select nombre, nivel_o_modalidad from public.inspectores where user_id = p.id order by id limit 1) i on true
    where p.role = 'areal' and p.active
      and (coalesce(btrim(p_busqueda), '') = '' or concat_ws(' ', i.nombre, p.name, i.nivel_o_modalidad)
        ilike '%' || replace(replace(replace(btrim(p_busqueda), '\', '\\'), '%', '\%'), '_', '\_') || '%')
  ), pagina as (select *, row_number() over (order by lower(nombre), id) posicion from filtradas
    order by lower(nombre), id limit p_lim offset p_offset)
  select jsonb_build_object('total', (select count(*) from filtradas),
    'filas', coalesce((select jsonb_agg(to_jsonb(pagina) - 'posicion' order by posicion) from pagina), '[]'::jsonb)) into resultado;
  return resultado;
end $$;
revoke all on function public.proyectos_areales_inspectores(text,integer,integer) from public, anon;
grant execute on function public.proyectos_areales_inspectores(text,integer,integer) to authenticated;

