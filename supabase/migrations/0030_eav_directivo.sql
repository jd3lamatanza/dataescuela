-- Escuela de Verano (rol escolar): directivo de la EAV, independiente de la tabla de directivos

create table public.eav_estados (
  id bigint generated by default as identity primary key,
  nombre text not null unique,
  color text not null check (color in ('green','blue','orange','red','cyan','violet','amber','slate')),
  orden integer not null default 0
);
alter table public.eav_estados enable row level security;
create policy eavest_sel on public.eav_estados for select to authenticated using (true);
create policy eavest_adm on public.eav_estados for all to authenticated using (public.is_admin()) with check (public.is_admin());
insert into public.eav_estados (nombre, color, orden) values
  ('Pendiente Aprobación', 'amber', 1), ('Aprobado', 'green', 2), ('Devuelto para Corrección', 'orange', 3), ('Rechazado', 'red', 4);

create table public.eav_directivos (
  id bigint generated by default as identity primary key,
  cue text not null unique,
  clave text,
  user_id uuid not null references public.profiles (id) on delete cascade,
  nombre text not null,
  cuil text not null check (cuil ~ '^[0-9]{11}$'),
  fecha_nacimiento date not null,
  cargo_base text not null,
  pat text,
  pid text,
  email text not null,
  telefono text not null check (telefono ~ '^[0-9]{6,15}$'),
  domicilio text not null,
  estado_id bigint not null references public.eav_estados (id),
  drive_folder_id text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.eav_directivo_archivos (
  id bigint generated by default as identity primary key,
  directivo_id bigint not null references public.eav_directivos (id) on delete cascade,
  nombre text not null,
  mime text,
  bytes bigint,
  drive_file_id text not null,
  created_at timestamptz not null default now()
);
create index eav_dir_arch_idx on public.eav_directivo_archivos (directivo_id);

alter table public.eav_directivos enable row level security;
alter table public.eav_directivo_archivos enable row level security;
-- Escritura solo por las funciones de abajo y la función de Drive (service role)
create policy eavdir_sel on public.eav_directivos for select to authenticated using (
  public.app_role() in ('admin','regional','distrital') or (public.app_role() = 'escolar' and cue = public.app_cue()));
create policy eavarch_sel on public.eav_directivo_archivos for select to authenticated using (
  exists (select 1 from public.eav_directivos d where d.id = directivo_id));

create or replace function public.eav_directivo_editable(p_id bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.eav_directivos d join public.eav_estados s on s.id = d.estado_id
    where d.id = p_id and public.app_role() = 'escolar' and d.cue = public.app_cue() and s.nombre <> 'Aprobado')
$$;

create or replace function public.eav_directivo_guardar(
  p_nombre text, p_cuil text, p_nacimiento date, p_cargo text, p_pat text, p_pid text, p_email text, p_tel text, p_domicilio text
) returns bigint
language plpgsql security definer set search_path = public as $$
declare e public.escuelas; d public.eav_directivos; v_id bigint; v_pend bigint;
begin
  if public.app_role() is distinct from 'escolar' then raise exception 'Solo las escuelas cargan el directivo de la EAV'; end if;
  select * into e from public.escuelas where cue = public.app_cue() order by id limit 1;
  if not found then raise exception 'No se encontró la escuela de tu usuario'; end if;
  if e.eav is distinct from 'Sí' then raise exception 'Activá primero la opción de escuela de verano'; end if;
  if length(trim(coalesce(p_nombre, ''))) < 3 or length(p_nombre) > 150 then raise exception 'Ingresá el nombre completo'; end if;
  if coalesce(p_cuil, '') !~ '^[0-9]{11}$' then raise exception 'El CUIL debe tener 11 números'; end if;
  if p_nacimiento is null or p_nacimiento >= current_date or p_nacimiento < date '1930-01-01' then raise exception 'Fecha de nacimiento inválida'; end if;
  if length(trim(coalesce(p_cargo, ''))) < 2 or length(p_cargo) > 150 then raise exception 'Ingresá el cargo base'; end if;
  if length(coalesce(p_pat, '')) > 100 or length(coalesce(p_pid, '')) > 100 then raise exception 'PAT o PID demasiado largo'; end if;
  if lower(trim(coalesce(p_email, ''))) !~ '^[a-z0-9._%+-]+@abc\.gob\.ar$' then raise exception 'El email debe ser @abc.gob.ar'; end if;
  if coalesce(p_tel, '') !~ '^[0-9]{6,15}$' then raise exception 'El teléfono debe tener solo números (6 a 15)'; end if;
  if length(trim(coalesce(p_domicilio, ''))) < 3 or length(p_domicilio) > 250 then raise exception 'Ingresá el domicilio'; end if;

  select * into d from public.eav_directivos where cue = e.cue;
  v_pend := (select id from public.eav_estados where nombre = 'Pendiente Aprobación');
  if found then
    if not public.eav_directivo_editable(d.id) then raise exception 'El directivo está aprobado y no se puede modificar'; end if;
    update public.eav_directivos set nombre = trim(p_nombre), cuil = p_cuil, fecha_nacimiento = p_nacimiento, cargo_base = trim(p_cargo),
      pat = nullif(trim(p_pat), ''), pid = nullif(trim(p_pid), ''), email = lower(trim(p_email)), telefono = p_tel, domicilio = trim(p_domicilio),
      estado_id = v_pend, updated_at = now() where id = d.id;
    return d.id;
  end if;
  insert into public.eav_directivos (cue, clave, user_id, nombre, cuil, fecha_nacimiento, cargo_base, pat, pid, email, telefono, domicilio, estado_id)
  values (e.cue, e.clave, public.eff_uid(), trim(p_nombre), p_cuil, p_nacimiento, trim(p_cargo), nullif(trim(p_pat), ''), nullif(trim(p_pid), ''),
          lower(trim(p_email)), p_tel, trim(p_domicilio), v_pend)
  returning id into v_id;
  return v_id;
end $$;
revoke all on function public.eav_directivo_guardar(text, text, date, text, text, text, text, text, text) from public, anon;
grant execute on function public.eav_directivo_guardar(text, text, date, text, text, text, text, text, text) to authenticated;
revoke all on function public.eav_directivo_editable(bigint) from public, anon;
grant execute on function public.eav_directivo_editable(bigint) to authenticated;
