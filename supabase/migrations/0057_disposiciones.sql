create table public.disposiciones (
  id bigint generated by default as identity primary key,
  estado text not null default 'En proceso' check (estado in ('En proceso','Enviada a SAD','Rechazada','Finalizada')),
  fecha_registro timestamptz not null default now(),
  inspector text not null,
  email_jefatura text not null,
  docente_nombre text not null,
  docente_cuil text not null,
  docente_email text not null,
  escuela_cubrir_id bigint not null references public.escuelas(id),
  escuela_cubrir_clave text not null,
  escuela_cubrir_nombre text not null,
  cargo_cubrir text not null,
  revista_cubrir text not null,
  tipo text not null,
  motivo text not null,
  fecha_designacion date not null,
  numero_designacion text not null,
  escuela_base_id bigint references public.escuelas(id),
  escuela_base_clave text not null,
  escuela_base_nombre text not null,
  cargo_base text not null,
  revista_base text not null,
  fecha_desde date not null,
  observaciones text not null default '',
  usuario text not null,
  actualizada timestamptz not null default now(),
  foreign key (tipo, motivo) references public.disposicion_motivos(tipo, motivo)
);
create index disposiciones_escuela_cubrir_idx on public.disposiciones(escuela_cubrir_id);
create index disposiciones_escuela_base_idx on public.disposiciones(escuela_base_id);

create function public.disposicion_validar() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if auth.uid() is null then return new; end if;
  if not public.disposiciones_permitido() then raise exception 'Sin permiso'; end if;
  if new.escuela_base_id is null and (tg_op = 'INSERT' or old.escuela_base_id is not null) then
    raise exception 'Seleccioná una escuela base';
  end if;
  select clave, coalesce(nullif(nombre, ''), concat_ws(' ', tipo, numero))
    into new.escuela_cubrir_clave, new.escuela_cubrir_nombre from public.escuelas where id = new.escuela_cubrir_id;
  if not found then raise exception 'Escuela a cubrir inexistente'; end if;
  if new.escuela_base_id is null then
    new.escuela_base_clave := old.escuela_base_clave;
    new.escuela_base_nombre := old.escuela_base_nombre;
  else
    select clave, coalesce(nullif(nombre, ''), concat_ws(' ', tipo, numero))
      into new.escuela_base_clave, new.escuela_base_nombre from public.escuelas where id = new.escuela_base_id;
    if not found then raise exception 'Escuela base inexistente'; end if;
  end if;
  if btrim(new.inspector) = '' or btrim(new.docente_nombre) = '' or new.docente_cuil !~ '^[0-9]+$'
    or new.email_jefatura !~* '^[^[:space:]@]+@abc\.gob\.ar$'
    or new.docente_email !~* '^[^[:space:]@]+@abc\.gob\.ar$'
    or new.cargo_cubrir not in ('Director','Vicedirector','Secretario','Prosecretario')
    or new.revista_cubrir not in ('Titular','Provisional','Suplente')
    or new.revista_base not in ('Titular','Provisional','Suplente')
    or btrim(new.numero_designacion) = '' or btrim(new.cargo_base) = '' then
    raise exception 'Completá los datos obligatorios con valores válidos';
  end if;
  select coalesce(nullif(name, ''), login) into new.usuario from public.profiles where id = public.eff_uid();
  new.actualizada := now();
  if tg_op = 'INSERT' then
    new.fecha_registro := now();
    new.estado := 'En proceso';
  else
    new.fecha_registro := old.fecha_registro;
  end if;
  return new;
end $$;

create table public.disposicion_archivos (
  id bigint generated by default as identity primary key,
  disposicion_id bigint not null references public.disposiciones(id) on delete cascade,
  nombre text not null,
  mime text not null,
  bytes bigint not null,
  drive_file_id text not null unique
);
create index disposicion_archivos_disposicion_idx on public.disposicion_archivos(disposicion_id);

create function public.disposiciones_permitido() returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce(public.app_role() = 'distrital' and public.real_role() = 'distrital', false)
$$;

create trigger disposicion_validar before insert or update on public.disposiciones
  for each row execute function public.disposicion_validar();

alter table public.disposicion_motivos enable row level security;
alter table public.disposiciones enable row level security;
alter table public.disposicion_archivos enable row level security;
create policy disposicion_motivos_lectura on public.disposicion_motivos for select to authenticated using (public.disposiciones_permitido());
create policy disposiciones_lectura on public.disposiciones for select to authenticated using (public.disposiciones_permitido());
create policy disposiciones_alta on public.disposiciones for insert to authenticated with check (public.disposiciones_permitido());
create policy disposiciones_edicion on public.disposiciones for update to authenticated using (public.disposiciones_permitido()) with check (public.disposiciones_permitido());
create policy disposicion_archivos_lectura on public.disposicion_archivos for select to authenticated using (public.disposiciones_permitido());

create function public.disposicion_archivo_limite() returns trigger
language plpgsql set search_path = public as $$
begin
  perform pg_advisory_xact_lock(new.disposicion_id);
  if (select count(*) from public.disposicion_archivos where disposicion_id = new.disposicion_id) >= 3 then
    raise exception 'Solo se permiten hasta 3 archivos de probanza';
  end if;
  return new;
end $$;
create trigger disposicion_archivo_limite before insert on public.disposicion_archivos
  for each row execute function public.disposicion_archivo_limite();

