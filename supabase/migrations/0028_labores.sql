create table public.labores (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles (id) on delete cascade,
  autor text not null,
  fecha date not null,
  lugar_id bigint not null references public.catalogos (id),
  tipo_id bigint not null references public.catalogos (id),
  dimension_id bigint not null references public.catalogos (id),
  evento_id bigint not null references public.catalogos (id),
  motivo text not null check (length(trim(motivo)) between 3 and 300),
  acuerdos text,
  equipo boolean not null default false,
  drive_folder_id text,
  drive_info_id text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index labores_fecha_idx on public.labores (fecha desc, id desc);
create index labores_user_idx on public.labores (user_id);

create table public.labor_inspectores (
  labor_id bigint not null references public.labores (id) on delete cascade,
  user_id uuid not null references public.profiles (id) on delete cascade,
  nombre text not null,
  primary key (labor_id, user_id)
);
create index labor_insp_user_idx on public.labor_inspectores (user_id);

create table public.labor_archivos (
  id bigint generated by default as identity primary key,
  labor_id bigint not null references public.labores (id) on delete cascade,
  nombre text not null,
  mime text,
  bytes bigint,
  drive_file_id text not null,
  created_at timestamptz not null default now()
);
create index labor_arch_labor_idx on public.labor_archivos (labor_id, id);

create or replace function public._labor_visible(p_id bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from public.labores l
    where l.id = p_id and (
      public.app_role() in ('admin','regional','distrital')
      or l.user_id = public.eff_uid()
      or exists (select 1 from public.labor_inspectores li where li.labor_id = l.id and li.user_id = public.eff_uid())))
$$;

create or replace function public.labor_es_autor(p_id bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.labores where id = p_id and user_id = public.eff_uid() and public.app_role() = 'areal')
$$;

